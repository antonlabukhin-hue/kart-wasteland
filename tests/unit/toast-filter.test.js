import { describe, it, expect } from 'vitest';
import { toastWanted } from '../../src/toast-filter.js';

describe('Пустошь: надписи в заезде — только важное', () => {
    it('оставляет потерю сердца, нападения, босса, «В ударе»', () => {
        ['🐺 Волк −½ ♥', '💥 Авария −1 ♥', '🐺 ВЦЕПИЛСЯ В КАПОТ!', '💪 Стряхнул!', '🐺 Увернулся! ×2', '🚨 БОСС НА ХВОСТЕ', '🔥 В УДАРЕ!', '🏆 НОВЫЙ РЕКОРД']
            .forEach((t) => expect(toastWanted('penalty-pop', t)).toBe(true));
    });
    it('убирает радио, подсказки и мелкие штрафы', () => {
        expect(toastWanted('radio-line', 'Осторожней, курьер. Аванс уже съели.')).toBe(false);
        ['💨 За попуткой копится нитро', 'Обломки! −0.8с', '🚚 Лобовое!', 'Перелёт!', '✨ Чистый отрезок — +20 Е', '✔ Чисто!', '🔥 Нитро готово — жми E', '★ Ушастик — Вёрткая: руль острее на 15%']
            .forEach((t) => expect(toastWanted('penalty-pop', t)).toBe(false));
    });
});
