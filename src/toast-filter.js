/**
 * Пустошь: надписей в заезде слишком много — прочитать их не успеваешь, а они закрывают дорогу.
 * Оставляем только то, что меняет игру сейчас: потеря сердца, нападение зверя («Вцепился», «Стряхнул», «Увернулся»),
 * босс на хвосте, «В ударе», рекорд, второй шанс. Остальное (радио, подсказки, «Обломки −0.8с», «Лобовое!»,
 * «Перелёт!», «+N Е», «Чисто!», пассивки машин) не показывается.
 *
 * toastWanted(cls, text) — показывать ли надпись (чистая функция, тест). cls — строка классов элемента.
 */
export const DROP_CLASSES = ['radio-line', 'story-plaque'];
export const NOISE = /попутк|Обломки!|Лобовое|Перелёт|Чист(ый|о!)|Задел|Скольз|Нитро готово|Вёрткая|руль острее|«На волоске|На волоске|Отскочил|\+\d+ ?Е\b|Е за|за две|ГОРЯЧИЙ СТАРТ|ПЕЙЗАЖ НЕДЕЛИ|Кузов помнит|курьер|Аванс|Тормоз|занос|снова полные/i;
export const KEEP = /♥|Вцепился|ВЦЕПИЛСЯ|Стряхнул|Увернулся|Ушёл от тарана|БОСС|Босс|В УДАРЕ|РЕКОРД|ВТОРОЙ ШАНС|РАЗБИЛСЯ|ПОЙМАЛ/;

export function toastWanted(cls, text) {
    const c = ' ' + (cls || '') + ' ', t = String(text || '');
    if (KEEP.test(t)) return true;
    if (DROP_CLASSES.some(function(k) { return c.indexOf(' ' + k + ' ') >= 0; })) return false;
    return !NOISE.test(t);
}
